"""Tests for self-contained HTML report export."""

from __future__ import annotations

from pathlib import Path

import pytest

from data_studio.kernel.provenance import Provenance
from data_studio.kernel.results import AnalysisResult, Diagnostic, ResultTable
from data_studio.kernel.spec import ChartSpec, ChartType, Encoding
from data_studio.reporting import render_html_report, write_html_report


def make_result(
    *,
    title: str = "Revenue by region",
    narrative: str = "North earns more than South.",
    kind: str = "descriptive_stats",
) -> AnalysisResult:
    return AnalysisResult(
        kind=kind,
        title=title,
        provenance=Provenance.create(
            dataset="sales",
            dataset_fingerprint="abc123",
            step_ids=("clean",),
            engine="duckdb",
            parameters={"column": "amount"},
        ),
        params={"column": "amount", "group": "region"},
        tables=(
            ResultTable(
                title="Summary",
                columns=("region", "mean"),
                rows=(("North", 15.5), ("South", 8.25)),
                note="Means exclude missing values.",
            ),
        ),
        metrics={"n": 12, "p_value": 0.0123, "significant": True, "missing": None},
        diagnostics=(
            Diagnostic.info("sample", "Twelve complete observations."),
            Diagnostic.warning("outliers", "One high leverage point was found."),
        ),
        narrative=narrative,
        charts=(
            ChartSpec(
                chart_type=ChartType.COLUMN,
                title="Amount by region",
                encoding=Encoding(x="region", y="amount"),
                data=(
                    {"region": "North", "amount": 15.5},
                    {"region": "South", "amount": 8.25},
                ),
            ),
        ),
    )


def test_report_embeds_every_result_surface() -> None:
    html = render_html_report(make_result(), generated_at="2026-01-02T03:04:05+00:00")

    assert html.startswith("<!DOCTYPE html>")
    assert "<title>Data Studio report</title>" in html
    assert "Revenue by region" in html
    assert "North earns more than South." in html
    assert "Amount by region" in html
    assert "<svg" in html
    assert "Summary" in html
    assert "Means exclude missing values." in html
    assert "Twelve complete observations." in html
    assert "One high leverage point was found." in html
    assert "Result ID" in html
    assert "2026-01-02T03:04:05+00:00" in html
    assert "Generated by Data Studio" in html


def test_report_is_self_contained_and_script_free() -> None:
    html = render_html_report([make_result(), make_result(title="Second result")])

    assert "<script" not in html.lower()
    assert "src=" not in html
    assert "@import" not in html
    # The only URL allowed is the SVG namespace declaration.
    assert html.count("http") == html.count("http://www.w3.org/2000/svg")


def test_report_escapes_untrusted_content() -> None:
    result = make_result(
        title="<script>alert('title')</script>",
        narrative="Danger & <b>markup</b>",
    )
    html = render_html_report(result)

    assert "<script>alert" not in html
    assert "&lt;script&gt;" in html
    assert "Danger &amp; &lt;b&gt;markup&lt;/b&gt;" in html


def test_report_formats_metrics_and_missing_values() -> None:
    html = render_html_report(make_result())

    assert "P value" in html
    assert "0.0123" in html
    assert ">Yes<" in html
    assert "—" in html


def test_dark_theme_is_applied() -> None:
    light = render_html_report(make_result(), theme="light")
    dark = render_html_report(make_result(), theme="dark")
    assert "#ffffff" in light
    assert "#0f172a" in dark
    assert 'class="theme-light"' in light
    assert 'class="theme-dark"' in dark
    assert "body.theme-dark" in dark
    assert light != dark


def test_write_report_creates_parent_directories(tmp_path: Path) -> None:
    destination = tmp_path / "reports" / "nested" / "analysis.html"
    written = write_html_report(make_result(), destination)

    assert written == destination
    assert destination.is_file()
    assert "Revenue by region" in destination.read_text(encoding="utf-8")


def test_report_validation() -> None:
    with pytest.raises(ValueError):
        render_html_report([])
    with pytest.raises(TypeError):
        render_html_report(["not-a-result"])  # type: ignore[list-item]
    with pytest.raises(ValueError):
        render_html_report(make_result(), title="  ")
    with pytest.raises(ValueError):
        render_html_report(make_result(), theme="neon")
    with pytest.raises(IsADirectoryError):
        write_html_report(make_result(), Path("."))
